def _setup_mock_ai(tc):
    r = tc.put("/api/v1/settings/ai", json={"provider": "mock", "set_active": True})
    assert r.status_code == 200


def _upload_and_confirm(
    tc,
    pid: str,
    filename: str,
    csv_text: str,
    *,
    report_type: str,
    market: str = "VN",
    locale: str = "en-US",
    research_request_id: str | None = None,
    target_keyword: str | None = None,
):
    data = {"report_type": report_type, "locale": locale}
    if research_request_id:
        data["research_request_id"] = research_request_id
    if target_keyword:
        data["target_keyword"] = target_keyword
    prev = tc.post(
        f"/api/v1/projects/{pid}/imports/preview",
        data=data,
        files={"file": (filename, csv_text.encode("utf-8"), "text/csv")},
    )
    assert prev.status_code == 200, prev.text
    pbody = prev.json()
    confirm_payload = {
        "upload_id": pbody["upload_id"],
        "research_request_id": research_request_id,
        "report_type": report_type,
        "market": market,
        "locale": locale,
        "column_mapping": pbody["suggested_mapping"],
    }
    if target_keyword:
        confirm_payload["target_keyword"] = target_keyword
    conf = tc.post(f"/api/v1/projects/{pid}/imports/confirm", json=confirm_payload)
    assert conf.status_code == 200, conf.text
    return conf.json()


def test_g1_g5_g6_g8_per_keyword_serp_isolation_and_no_draft_bypass(client):
    """
    G1: Project has SERP for keyword A only, metrics for A and B; B approved -> B official=False, SERP_NOT_VERIFIED.
    G5: allow_draft=True MUST NOT silently create OFFICIAL brief for ineligible B.
    G6: Missing SERP -> DRAFT stamped SERP_NOT_VERIFIED.
    G8: 1-2 URLs cannot claim TOP_10_VERIFIED or make keyword OFFICIAL.
    """
    tc, _ = client
    _setup_mock_ai(tc)
    pid = tc.post(
        "/api/v1/projects",
        json={
            "code": "QA01",
            "name": "Thuế doanh nghiệp",
            "topic_pillar_code": "QA01",
            "topic_pillar_name": "Thuế doanh nghiệp",
            "primary_keyword": "quyết toán thuế tndn",
            "secondary_keywords": ["công cụ tính thuế tndn"],
            "business_goal": "Tăng khách hàng B2B kế toán",
            "target_audience": "Kế toán trưởng SME",
            "market": "VN",
        },
    ).json()["project"]["id"]

    tc.post(f"/api/v1/projects/{pid}/analyze-topic")

    # Metrics for ALL 3 demand groups generated by mock analyst
    metrics_csv = (
        "Keyword,Volume,KD,Intent\n"
        "quyết toán thuế tndn,1200,25,Informational\n"
        "cách xử lý quyết toán thuế tndn,300,18,Informational\n"
        "công cụ tính thuế tndn,450,20,Transactional\n"
    )
    _upload_and_confirm(tc, pid, "metrics.csv", metrics_csv, report_type="KEYWORD_OVERVIEW")

    # G8: Upload only 2 organic URLs for keyword A first -> MUST be PARTIAL_SERP_EVIDENCE, NOT official!
    partial_serp = (
        "Keyword,Position,URL,Title\n"
        "quyết toán thuế tndn,1,https://example.vn/blog/qt-1,QT 1\n"
        "quyết toán thuế tndn,2,https://example.vn/blog/qt-2,QT 2\n"
    )
    _upload_and_confirm(tc, pid, "serp_partial.csv", partial_serp, report_type="ORGANIC_RESULTS")
    tc.post(f"/api/v1/projects/{pid}/mapping/preview")
    for a in tc.get(f"/api/v1/projects/{pid}/approvals").json()["approvals"]:
        if a["status"] == "PENDING":
            tc.post(f"/api/v1/projects/{pid}/approvals/{a['id']}", json={"decision": "APPROVED"})

    opps_partial = tc.get(f"/api/v1/projects/{pid}/opportunities").json()
    m_a = next(m for m in opps_partial["mappings"] if m["primary_keyword"] == "quyết toán thuế tndn")
    assert m_a["eligibility"]["eligible_official"] is False
    assert m_a["eligibility"]["top10_verified"] is False
    assert m_a["eligibility"]["serp_tier"] == "PARTIAL_SERP_EVIDENCE"

    # Now add positions 3..5 for keyword A ONLY (still ZERO SERP for keyword B!)
    more_serp_a = (
        "Keyword,Position,URL,Title\n"
        "quyết toán thuế tndn,3,https://example.vn/blog/qt-3,QT 3\n"
        "quyết toán thuế tndn,4,https://example.vn/blog/qt-4,QT 4\n"
        "quyết toán thuế tndn,5,https://example.vn/blog/qt-5,QT 5\n"
    )
    _upload_and_confirm(tc, pid, "serp_a_more.csv", more_serp_a, report_type="ORGANIC_RESULTS")
    tc.post(f"/api/v1/projects/{pid}/mapping/preview")

    # Approve ALL pending mappings (including B: 'cách xử lý quyết toán thuế tndn')
    for a in tc.get(f"/api/v1/projects/{pid}/approvals").json()["approvals"]:
        if a["status"] == "PENDING":
            r = tc.post(f"/api/v1/projects/{pid}/approvals/{a['id']}", json={"decision": "APPROVED"})
            assert r.status_code == 200

    opps = tc.get(f"/api/v1/projects/{pid}/opportunities").json()
    by_kw = {m["primary_keyword"]: m for m in opps["mappings"]}
    map_a = by_kw["quyết toán thuế tndn"]
    map_b = by_kw["cách xử lý quyết toán thuế tndn"]

    # G1: A has >=3 valid organic URLs & approval -> official=True (but NOT top10_verified because only 5 ranks!)
    assert map_a["eligibility"]["eligible_official"] is True
    assert map_a["eligibility"]["top10_verified"] is False
    # G1: B has ZERO organic URLs for B -> MUST stay SERP_NOT_VERIFIED and eligible_official=False!
    assert map_b["eligibility"]["eligible_official"] is False
    assert map_b["serp_status"] == "SERP_NOT_VERIFIED"

    # G5 & G6: allow_draft=True MUST produce OFFICIAL for A and DRAFT + SERP_NOT_VERIFIED for B!
    gen = tc.post(f"/api/v1/projects/{pid}/briefs/generate", json={"allow_draft": True})
    assert gen.status_code == 200
    briefs_by_kw = {b["primary_keyword"]: b for b in gen.json()["briefs"]}
    assert briefs_by_kw["quyết toán thuế tndn"]["brief_mode"] == "OFFICIAL"
    assert briefs_by_kw["cách xử lý quyết toán thuế tndn"]["brief_mode"] == "DRAFT"
    assert briefs_by_kw["cách xử lý quyết toán thuế tndn"]["status"] == "SERP_NOT_VERIFIED"

    # Direct allow_draft=False for ineligible B MUST be rejected (400)
    deny_b = tc.post(
        f"/api/v1/projects/{pid}/briefs/generate",
        json={"allow_draft": False, "mapping_ids": [map_b["id"]]},
    )
    assert deny_b.status_code == 400


