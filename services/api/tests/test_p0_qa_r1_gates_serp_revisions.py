def test_m1_m2_m3_m4_m5_m6_revision_safety_stale_approval_and_brief_invalidation(client):
    """
    M1: Rerun mapping preview with unchanged inputs -> idempotent IDs, zero duplicate approvals.
    M2: Material change (evidence/URL/page_type) invalidates old approval & fingerprint.
    M3: Attempting to approve an obsolete/superseded approval ID -> 409 Conflict, no mutation.
    M4: Rejected / NEED_MORE_EVIDENCE stays blocked.
    M5: Cross-project approval ID denied.
    M6: Existing OFFICIAL brief & BriefVersions survive rebuild, marked stale when mapping/evidence changes.
    """
    tc, _ = client
    _setup_mock_ai(tc)
    pid = tc.post(
        "/api/v1/projects",
        json={
            "code": "QA03",
            "name": "Hóa đơn đầu vào",
            "topic_pillar_code": "QA03",
            "topic_pillar_name": "Hóa đơn đầu vào",
            "primary_keyword": "hóa đơn đầu vào hợp lệ",
            "business_goal": "Tư vấn kế toán thuế B2B",
            "target_audience": "Kế toán doanh nghiệp",
            "market": "VN",
        },
    ).json()["project"]["id"]
    other_pid = tc.post(
        "/api/v1/projects",
        json={"code": "QA99", "name": "Dự án khác", "primary_keyword": "chi phí hợp lý"},
    ).json()["project"]["id"]

    metrics_csv = "Keyword,Volume,KD,Intent\nhóa đơn đầu vào hợp lệ,880,22,Informational\n"
    _upload_and_confirm(tc, pid, "m1.csv", metrics_csv, report_type="KEYWORD_OVERVIEW")
    serp_csv = (
        "Keyword,Position,URL,Title\n"
        "hóa đơn đầu vào hợp lệ,1,https://ex.vn/blog/1,Bai 1\n"
        "hóa đơn đầu vào hợp lệ,2,https://ex.vn/blog/2,Bai 2\n"
        "hóa đơn đầu vào hợp lệ,3,https://ex.vn/blog/3,Bai 3\n"
    )
    _upload_and_confirm(tc, pid, "s1.csv", serp_csv, report_type="ORGANIC_RESULTS")

    # M1: Run preview twice with same inputs -> stable ID, no duplicate approvals
    r1 = tc.post(f"/api/v1/projects/{pid}/mapping/preview").json()
    opps1 = tc.get(f"/api/v1/projects/{pid}/opportunities").json()
    aprs1 = tc.get(f"/api/v1/projects/{pid}/approvals").json()["approvals"]
    assert len(aprs1) == 1
    orig_mapping_id = opps1["mappings"][0]["id"]
    orig_apr_id = aprs1[0]["id"]

    r2 = tc.post(f"/api/v1/projects/{pid}/mapping/preview").json()
    opps2 = tc.get(f"/api/v1/projects/{pid}/opportunities").json()
    aprs2 = tc.get(f"/api/v1/projects/{pid}/approvals").json()["approvals"]
    assert opps2["mappings"][0]["id"] == orig_mapping_id
    assert len(aprs2) == 1  # No duplicate approvals!
    assert r2["approvals_created"] == 0

    # M5: Cross-project approval ID MUST be denied!
    cross = tc.post(f"/api/v1/projects/{other_pid}/approvals/{orig_apr_id}", json={"decision": "APPROVED"})
    assert cross.status_code in (403, 404)

    # Approve and generate OFFICIAL brief
    ok_apr = tc.post(f"/api/v1/projects/{pid}/approvals/{orig_apr_id}", json={"decision": "APPROVED"})
    assert ok_apr.status_code == 200
    br = tc.post(f"/api/v1/projects/{pid}/briefs/generate", json={"allow_draft": False})
    assert br.status_code == 200
    assert br.json()["official_count"] == 1
    orig_brief_id = br.json()["briefs"][0]["id"]

    # M3: Replaying already-decided approval -> 409 Conflict
    replay = tc.post(f"/api/v1/projects/{pid}/approvals/{orig_apr_id}", json={"decision": "APPROVED"})
    assert replay.status_code == 409

    # M2 & M6: Upload NEW organic evidence shifting dominant page_type to TOOL -> material change!
    serp_tool_csv = (
        "Keyword,Position,URL,Title\n"
        "hóa đơn đầu vào hợp lệ,1,https://ex.vn/cong-cu/tinh-hd-1,Công cụ 1\n"
        "hóa đơn đầu vào hợp lệ,2,https://ex.vn/cong-cu/tinh-hd-2,Công cụ 2\n"
        "hóa đơn đầu vào hợp lệ,3,https://ex.vn/cong-cu/tinh-hd-3,Công cụ 3\n"
        "hóa đơn đầu vào hợp lệ,4,https://ex.vn/cong-cu/tinh-hd-4,Công cụ 4\n"
    )
    _upload_and_confirm(tc, pid, "s_tool.csv", serp_tool_csv, report_type="ORGANIC_RESULTS")
    tc.post(f"/api/v1/projects/{pid}/mapping/preview")

    opps_after = tc.get(f"/api/v1/projects/{pid}/opportunities").json()
    m_after = opps_after["mappings"][0]
    # Stable ID preserved, revision incremented, old approval invalidated!
    assert m_after["id"] == orig_mapping_id
    assert m_after["page_type"] == "TOOL"
    assert m_after["is_approved"] is False
    assert m_after["eligibility"]["eligible_official"] is False

    # M6: Old brief SURVIVES with same ID, but is marked stale & downgraded to DRAFT!
    briefs_after = tc.get(f"/api/v1/projects/{pid}/briefs").json()["briefs"]
    assert len(briefs_after) == 1
    assert briefs_after[0]["id"] == orig_brief_id
    assert briefs_after[0]["is_stale"] is True
    assert briefs_after[0]["brief_mode"] == "DRAFT"

    # M4: Rejecting the new pending approval keeps mapping blocked!
    new_pending = [a for a in tc.get(f"/api/v1/projects/{pid}/approvals").json()["approvals"] if a["status"] == "PENDING"]
    assert len(new_pending) == 1
    rej = tc.post(f"/api/v1/projects/{pid}/approvals/{new_pending[0]['id']}", json={"decision": "REJECTED", "decision_note": "Chưa hợp lý"})
    assert rej.status_code == 200
    assert tc.post(f"/api/v1/projects/{pid}/briefs/generate", json={"allow_draft": False}).status_code == 400


def test_real_semrush_csv_fixtures_and_top10_verification(client):
    """
    Validate against the exact real Semrush CSV formats supplied by project owner:
    - File 1: Keyword,Volume,Keyword Difficulty (15 rows, empty KD, explicit 0 volume, no Intent column)
    - File 2: Position,Type,Domain,URL,... (5 AI Overview rows at pos 1 + 99 Organic rows with duplicates, NO Keyword column)
    """
    tc, _ = client
    _setup_mock_ai(tc)
    pid = tc.post(
        "/api/v1/projects",
        json={
            "code": "P01-REAL",
            "name": "Lương Net và Gross (Real Fixture)",
            "topic_pillar_code": "P01",
            "topic_pillar_name": "Lương Net & Gross",
            "primary_keyword": "lương net và gross là gì",
            "business_goal": "Tư vấn quản trị lương HR SME",
            "target_audience": "HR và nhân sự đi làm",
            "market": "VN",
        },
    ).json()["project"]["id"]

    # Create ResearchRequests so SERP file without Keyword column binds explicitly to seed_keyword
    reqs = tc.post(
        f"/api/v1/projects/{pid}/research-requests",
        json={
            "items": [
                {"seed_keyword": "lương net và gross là gì", "report_type": "KEYWORD_OVERVIEW", "market": "VN"},
                {"seed_keyword": "lương net và gross là gì", "report_type": "ORGANIC_RESULTS", "market": "VN"},
            ]
        },
    ).json()["research_requests"]

    metrics_text = (FIXTURES / "semrush_metrics_real_sample.csv").read_text(encoding="utf-8")
    serp_text = (FIXTURES / "semrush_serp_real_sample.csv").read_text(encoding="utf-8")

    m_conf = _upload_and_confirm(
        tc, pid, "real_metrics.csv", metrics_text,
        report_type="KEYWORD_OVERVIEW", research_request_id=reqs[0]["id"],
    )
    assert m_conf["total_raw_rows"] == 15

    s_conf = _upload_and_confirm(
        tc, pid, "real_serp.csv", serp_text,
        report_type="ORGANIC_RESULTS", research_request_id=reqs[1]["id"],
    )
    assert s_conf["total_raw_rows"] == 104  # 5 AI Overview + 99 Organic!

    ev = tc.get(f"/api/v1/projects/{pid}/evidence?row_type=ORGANIC_RESULTS&limit=200").json()
    ai_overview_rows = [r for r in ev["rows"] if r.get("serp_result_type") == "AI_OVERVIEW"]
    valid_organic_rows = [r for r in ev["rows"] if r.get("serp_result_type") == "ORGANIC" and r.get("organic_valid") and not r["is_duplicate"]]
    # Must distinguish AI Overview from Organic, bind keyword from request, and dedup duplicate URLs!
    assert len(ai_overview_rows) == 5
    assert all(r["organic_valid"] is False for r in ai_overview_rows)
    assert len(valid_organic_rows) >= 90
    assert all(r["keyword"] == "lương net và gross là gì" for r in valid_organic_rows)

    # Mapping + Approval -> TOP_10_VERIFIED & OFFICIAL Brief!
    tc.post(f"/api/v1/projects/{pid}/mapping/preview")
    aprs = tc.get(f"/api/v1/projects/{pid}/approvals").json()["approvals"]
    for a in aprs:
        if a["status"] == "PENDING":
            tc.post(f"/api/v1/projects/{pid}/approvals/{a['id']}", json={"decision": "APPROVED"})

    opps = tc.get(f"/api/v1/projects/{pid}/opportunities").json()
    m0 = opps["mappings"][0]
    assert m0["eligibility"]["serp_tier"] == "TOP_10_VERIFIED"
    assert m0["eligibility"]["top10_verified"] is True
    assert m0["eligibility"]["eligible_official"] is True

    br = tc.post(f"/api/v1/projects/{pid}/briefs/generate", json={"allow_draft": False})
    assert br.status_code == 200
    assert br.json()["official_count"] == 1
